            ProfanityLevel.CLEAN -> praiseClean
            ProfanityLevel.MILD -> praiseClean + praiseSpicy.take(3)
            else -> praiseClean + praiseSpicy
        }
        return pool[seed.mod(pool.size).let { if (it < 0) it + pool.size else it }]
    }


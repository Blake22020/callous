object VerbalAssault {

    fun insult(
        level: ProfanityLevel,
        seed: Int = (0..9999).random(),
        userName: String = "",
        habitTitle: String = ""
    ): String {
        val pool = when (level) {
            ProfanityLevel.CLEAN -> clean
            ProfanityLevel.MILD -> mild
            ProfanityLevel.SAVAGE -> savage
            ProfanityLevel.NIGHTMARE -> nightmare
        }
        val message = pick(pool, seed).replace("{habit}", habitTitle.ifBlank { "своё дело" })
        return personalize(message, userName, seed)
    }

    fun praise(
        level: ProfanityLevel,
        seed: Int = (0..9999).random(),
        userName: String = "",
        habitTitle: String = ""
    ): String {
        val pool = when (level) {
            ProfanityLevel.CLEAN -> praiseClean
            ProfanityLevel.MILD -> praiseMild
            ProfanityLevel.SAVAGE -> praiseSavage
            ProfanityLevel.NIGHTMARE -> praiseNightmare
        }
        val message = pick(pool, seed).replace("{habit}", habitTitle.ifBlank { "дело" })
        return personalize(message, userName, seed)
    }

    fun homeMessage(level: ProfanityLevel, done: Int, total: Int, userName: String = ""): String {
        val state = when {
            total == 0 -> 0
            done >= total -> 1
            done == 0 -> 2
            else -> 3
        }
        val pool = when (level) {
            ProfanityLevel.CLEAN -> homeClean
            ProfanityLevel.MILD -> homeMild
            ProfanityLevel.SAVAGE -> homeSavage
            ProfanityLevel.NIGHTMARE -> homeNightmare
        }
        return personalize(pool[state], userName, state)
    }

    fun reminder(level: ProfanityLevel, userName: String, detail: String): String {
        val pool = when (level) {
            ProfanityLevel.CLEAN -> reminderClean
            ProfanityLevel.MILD -> reminderMild
            ProfanityLevel.SAVAGE -> reminderSavage
            ProfanityLevel.NIGHTMARE -> reminderNightmare
        }
        val greeting = pool.random().replace("{name}", userName.ifBlank { "боец" })
        return "$greeting\n\n$detail"
    }

    fun sosIntro(level: ProfanityLevel, userName: String = ""): String {
        val line = when (level) {
            ProfanityLevel.CLEAN -> "Накрыло? Выбери состояние и прочитай план. Потом сделай первый маленький шаг."
            ProfanityLevel.MILD -> "Плохо? Выбери состояние, чёрт возьми, и сделай первый посильный шаг."
            ProfanityLevel.SAVAGE -> "Накрыло? Не разводи панику, блядь. Выбери состояние и выполни один шаг."
            ProfanityLevel.NIGHTMARE -> "Хреновый день? Выбирай состояние, сука, и делай первый шаг. Без самоуничтожения и геройства через травму."
        }
        return personalize(line, userName, 2)
    }

    private fun pick(pool: List<String>, seed: Int): String = pool[Math.floorMod(seed, pool.size)]

    private fun personalize(message: String, userName: String, seed: Int): String =
        if (userName.isNotBlank() && Math.floorMod(seed, 2) == 0) "$userName, $message" else message


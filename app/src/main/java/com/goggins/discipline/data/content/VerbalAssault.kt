    fun insult(level: ProfanityLevel, seed: Int = (0..9999).random()): String {
        val pool = when (level) {
            ProfanityLevel.CLEAN -> clean
            ProfanityLevel.MILD -> mild
            ProfanityLevel.SAVAGE -> savage
            ProfanityLevel.NIGHTMARE -> nightmare
        }
        return pool[seed.mod(pool.size).let { if (it < 0) it + pool.size else it }]
    }

    fun praise(level: ProfanityLevel, seed: Int = (0..9999).random()): String {
